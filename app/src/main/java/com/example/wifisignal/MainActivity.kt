package com.example.wifisignal

import android.Manifest
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.net.wifi.WifiManager
import android.os.Bundle
import android.os.Handler
import android.os.Looper
import android.widget.Button
import android.widget.CheckBox
import android.widget.EditText
import android.widget.TextView
import android.widget.Toast
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import androidx.core.content.ContextCompat
import androidx.core.content.FileProvider
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Wi-Fi Signal Mapper (Option C).
 *
 * - Reads the RSSI of the Wi-Fi network the phone is connected to, once per second,
 *   using WifiManager / WifiInfo.getRssi().
 * - Shows it live.
 * - "Record" saves 10 consecutive readings with a label, distance, wall flag and session
 *   number to readings.csv.
 *
 * Privacy: the SSID / BSSID (name / MAC of the network) are NOT read or saved.
 *
 * NOTE FOR AI-USAGE LOG (Appendix C): this file was first generated by an AI tool
 * (Claude). Mark below which parts you changed or wrote yourselves.
 */
class MainActivity : AppCompatActivity() {

    private data class Reading(val rssi: Int, val freqMhz: Int, val linkMbps: Int, val time: Long)

    companion object {
        private const val READINGS_PER_RECORD = 10
        private const val SAMPLE_INTERVAL_MS = 1000L
        private const val CSV_NAME = "readings.csv"
        private const val CSV_HEADER =
            "timestamp,session,label,distance_m,wall,band,freq_mhz,link_mbps,reading_no,rssi_dbm"
    }

    private lateinit var wifiManager: WifiManager
    private val handler = Handler(Looper.getMainLooper())

    private lateinit var tvRssi: TextView
    private lateinit var tvDetails: TextView
    private lateinit var tvStatus: TextView
    private lateinit var tvResult: TextView
    private lateinit var tvFile: TextView
    private lateinit var etLabel: EditText
    private lateinit var etDistance: EditText
    private lateinit var etSession: EditText
    private lateinit var cbWall: CheckBox
    private lateinit var btnRecord: Button
    private lateinit var btnShare: Button

    private var recording = false
    private val buffer = mutableListOf<Reading>()

    private val permissionLauncher =
        registerForActivityResult(ActivityResultContracts.RequestPermission()) { granted ->
            if (!granted) {
                tvStatus.text = "Location permission denied. Android needs it to read Wi-Fi signal."
            }
        }

    // ---- sampling loop: runs every second while the screen is visible ----
    private val sampler = object : Runnable {
        override fun run() {
            onSample()
            handler.postDelayed(this, SAMPLE_INTERVAL_MS)
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)

        wifiManager = applicationContext.getSystemService(Context.WIFI_SERVICE) as WifiManager

        tvRssi = findViewById(R.id.tvRssi)
        tvDetails = findViewById(R.id.tvDetails)
        tvStatus = findViewById(R.id.tvStatus)
        tvResult = findViewById(R.id.tvResult)
        tvFile = findViewById(R.id.tvFile)
        etLabel = findViewById(R.id.etLabel)
        etDistance = findViewById(R.id.etDistance)
        etSession = findViewById(R.id.etSession)
        cbWall = findViewById(R.id.cbWall)
        btnRecord = findViewById(R.id.btnRecord)
        btnShare = findViewById(R.id.btnShare)

        btnRecord.setOnClickListener { startRecording() }
        btnShare.setOnClickListener { shareCsv() }

        tvFile.text = "Log file: ${csvFile().absolutePath}"

        if (!hasPermission()) {
            permissionLauncher.launch(Manifest.permission.ACCESS_FINE_LOCATION)
        }
    }

    override fun onResume() {
        super.onResume()
        handler.post(sampler)
    }

    override fun onPause() {
        super.onPause()
        handler.removeCallbacks(sampler)
        if (recording) {
            // do not keep half a recording if the app is left
            recording = false
            buffer.clear()
            btnRecord.isEnabled = true
            tvResult.text = "Recording cancelled (app was paused). Please record again."
        }
    }

    private fun hasPermission() =
        ContextCompat.checkSelfPermission(this, Manifest.permission.ACCESS_FINE_LOCATION) ==
            PackageManager.PERMISSION_GRANTED

    /** Reads the current Wi-Fi info. Returns null if there is no usable reading. */
    @Suppress("DEPRECATION") // connectionInfo is deprecated on Android 12+ but still returns RSSI
    private fun readWifi(): Reading? {
        if (!hasPermission()) return null
        if (!wifiManager.isWifiEnabled) return null
        val info = wifiManager.connectionInfo ?: return null
        val rssi = info.rssi
        // -127 (or very small values) means "not connected / unknown"
        if (rssi <= -127 || rssi >= 0) return null
        return Reading(rssi, info.frequency, info.linkSpeed, System.currentTimeMillis())
    }

    private fun bandName(freqMhz: Int) = when {
        freqMhz in 2400..2500 -> "2.4GHz"
        freqMhz in 4900..5900 -> "5GHz"
        freqMhz >= 5925 -> "6GHz"
        else -> "unknown"
    }

    private fun onSample() {
        val r = readWifi()
        if (r == null) {
            tvRssi.text = "-- dBm"
            tvDetails.text = "Band: --   Link speed: --"
            tvStatus.text = when {
                !hasPermission() -> "Location permission needed."
                !wifiManager.isWifiEnabled -> "Wi-Fi is off. Turn it on and connect to your router."
                else -> "Not connected to a Wi-Fi network."
            }
            return
        }

        tvRssi.text = "${r.rssi} dBm"
        tvDetails.text = "Band: ${bandName(r.freqMhz)}   Link speed: ${r.linkMbps} Mbps"

        if (recording) {
            buffer.add(r)
            tvStatus.text = "Recording... ${buffer.size} / $READINGS_PER_RECORD"
            if (buffer.size >= READINGS_PER_RECORD) finishRecording()
        } else {
            tvStatus.text = "Ready. Hold the phone the same way every time."
        }
    }

    private fun startRecording() {
        if (readWifi() == null) {
            Toast.makeText(this, "No valid Wi-Fi reading yet. Check Wi-Fi and permission.", Toast.LENGTH_LONG).show()
            return
        }
        if (etDistance.text.toString().trim().toDoubleOrNull() == null) {
            Toast.makeText(this, "Enter the distance in metres first.", Toast.LENGTH_SHORT).show()
            return
        }
        buffer.clear()
        recording = true
        btnRecord.isEnabled = false
        tvResult.text = "Recording..."
    }

    private fun finishRecording() {
        recording = false
        btnRecord.isEnabled = true

        val distance = etDistance.text.toString().trim().toDouble()
        val wall = cbWall.isChecked
        val session = etSession.text.toString().trim().ifEmpty { "1" }
        var label = etLabel.text.toString().trim()
        if (label.isEmpty()) {
            val d = if (distance % 1.0 == 0.0) distance.toInt().toString() else distance.toString()
            label = "$d m, ${if (wall) "wall" else "no wall"}"
        }

        val file = csvFile()
        val newFile = !file.exists()
        val stamp = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
        file.appendText(buildString {
            if (newFile) append(CSV_HEADER).append('\n')
            buffer.forEachIndexed { i, r ->
                append(stamp.format(Date(r.time))).append(',')
                append(session).append(',')
                append('"').append(label.replace("\"", "\"\"")).append('"').append(',')
                append(distance).append(',')
                append(if (wall) "wall" else "no_wall").append(',')
                append(bandName(r.freqMhz)).append(',')
                append(r.freqMhz).append(',')
                append(r.linkMbps).append(',')
                append(i + 1).append(',')
                append(r.rssi).append('\n')
            }
        })

        val avg = buffer.map { it.rssi }.average()
        val min = buffer.minOf { it.rssi }
        val max = buffer.maxOf { it.rssi }
        tvResult.text = "Saved ${buffer.size} readings for \"$label\" (session $session).\n" +
            "Average: ${"%.1f".format(Locale.US, avg)} dBm   (min $min, max $max)\n" +
            "Total lines in file: ${file.readLines().size - 1}"
        buffer.clear()
    }

    private fun csvFile(): File {
        val dir = getExternalFilesDir(null) ?: filesDir
        return File(dir, CSV_NAME)
    }

    private fun shareCsv() {
        val file = csvFile()
        if (!file.exists()) {
            Toast.makeText(this, "Nothing saved yet.", Toast.LENGTH_SHORT).show()
            return
        }
        val uri = FileProvider.getUriForFile(this, "$packageName.fileprovider", file)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/csv"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        startActivity(Intent.createChooser(intent, "Share readings.csv"))
    }
}
